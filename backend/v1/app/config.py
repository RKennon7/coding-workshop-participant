"""Application settings, loaded once at import time into the `settings` singleton.

The Settings class reads from backend/v1/.env locally; real environment variables (set by Terraform
on Lambda/LocalStack) take priority. Imported by database.py (connection URL), security.py
(JWT secret + expiry) and main.py (CORS origins).
"""

from pathlib import Path

from pydantic import computed_field
from pydantic_settings import BaseSettings, SettingsConfigDict
from sqlalchemy.engine import URL

BASE_DIR = Path(__file__).resolve().parent.parent  # backend/v1


class Settings(BaseSettings):
    """Typed configuration. Each field maps to an env var of the same name, case-insensitive
    (e.g. POSTGRES_HOST, SECRET_KEY). `secret_key` has no default, so the app refuses to start without it.
    """
    # injected by Terraform in LocalStack/AWS, read from .env when running fastapi dev
    is_local: bool = False  # True turns on SQL echo and turns off the SSL requirement (see database.py)
    postgres_host: str = "localhost"
    postgres_port: int = 5432
    postgres_name: str = "postgres"
    postgres_user: str = "postgres"
    postgres_pass: str = ""

    secret_key: str  # signs JWTs; generated by Terraform in AWS
    cors_origins: list[str] = ["http://localhost:3000"]  # as an env var this must be a JSON list
    frontend_origin: str = "http://localhost:3000"  # not currently read anywhere in the backend
    access_token_expire_minutes: int = 30
    # refresh_token_expire_days: int = 7

    model_config = SettingsConfigDict(
        env_file=BASE_DIR / ".env",
        env_ignore_empty=True,  # an empty env var falls back to the default instead of overriding it with ""
        extra="ignore",  # .env may hold variables meant for other tools
    )

    @computed_field
    @property
    def database_url(self) -> str:
        """asyncpg connection URL built from the postgres_* fields.

        URL.create escapes special characters in the password; an empty password is omitted.
        hide_password=False because the result is handed to create_async_engine, not logged.
        """
        return URL.create(
            drivername="postgresql+asyncpg",
            username=self.postgres_user,
            password=self.postgres_pass or None,
            host=self.postgres_host,
            port=self.postgres_port,
            database=self.postgres_name,
        ).render_as_string(hide_password=False)


settings = Settings()